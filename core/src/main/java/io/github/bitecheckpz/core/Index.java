package io.github.bitecheckpz.core;

import java.io.IOException;
import java.nio.file.Path;
import java.time.Duration;
import java.time.Instant;
import java.time.format.DateTimeParseException;
import java.time.temporal.ChronoUnit;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The signed index the launcher downloads: one small file with the verification status of every
 * jar the registry knows, so players do not need a full registry checkout.
 *
 * <pre>
 * format = 1
 * generated_at = "2026-11-01T10:00:00Z"
 * registry_commit = "…"
 * [verified]
 * &lt;jar sha256&gt; = "mod-id 1.0.0"
 * [flagged]
 * &lt;jar sha256&gt; = "mod-id 1.0.0: reason"
 * [blocked]
 * &lt;jar sha256&gt; = "reason"
 * [compat]
 * &lt;jar sha256&gt; = "game >=42.13; zombiebuddy >=2.3"
 * </pre>
 *
 * <p>{@code [compat]} names the versions a verified jar's release was made for (see {@link Compat});
 * launchers from before it ignore the section.
 *
 * <p>The index is generated by CI from the registry ({@link #generate}) and signed with the registry
 * key. Jars that are not listed are unverified. A signed {@link Timestamp} can confirm later that the
 * index is still current ({@link #confirmedAt}), for at most {@link #MAX_CONFIRMED_AGE}.
 */
public final class Index {

    public static final int FORMAT = 1;
    /** After this age, verified entries are no longer trusted (blocked entries still apply). */
    public static final Duration MAX_AGE = Duration.ofDays(7);
    /** A timestamp keeps an index fresh for at most this long after it was generated. */
    public static final Duration MAX_CONFIRMED_AGE = Duration.ofDays(45);
    /** Tolerated clock difference for indexes that seem to come from the future. */
    public static final Duration CLOCK_SKEW = Duration.ofHours(1);

    /** {@code compat}: the versions the release was made for ({@link Compat#describe}), or null. */
    public record Entry(Verifier.Status status, String label, String compat) {
        public Entry(Verifier.Status status, String label) {
            this(status, label, null);
        }
    }

    private final Instant generatedAt;
    private final String registryCommit;
    private final Map<String, Entry> entries;
    private final Instant confirmedAt;
    /** {@code [notes]}: hash -> what players should know (open info/suspicion flags, review notes). */
    private final Map<String, String> notes;
    /** {@code [reviewers]}: verified hash -> the reviewers whose approval counted. */
    private final Map<String, List<String>> reviewers;

    private Index(Instant generatedAt, String registryCommit, Map<String, Entry> entries, Instant confirmedAt,
            Map<String, String> notes, Map<String, List<String>> reviewers) {
        this.generatedAt = generatedAt;
        this.registryCommit = registryCommit;
        this.entries = entries;
        this.confirmedAt = confirmedAt;
        this.notes = notes;
        this.reviewers = reviewers;
    }

    /** What players should know about this jar (open info or suspicion flags, review notes), or null. */
    public String note(String sha256) {
        return notes.get(sha256);
    }

    /** The reviewers whose approval made this jar verified; empty if the index does not say. */
    public List<String> reviewers(String sha256) {
        return reviewers.getOrDefault(sha256, List.of());
    }

    public Instant generatedAt() {
        return generatedAt;
    }

    public String registryCommit() {
        return registryCommit;
    }

    public Map<String, Entry> entries() {
        return entries;
    }

    /** Status of a jar hash: VERIFIED, FLAGGED, BLOCKED or UNVERIFIED (not listed). */
    public Entry lookup(String sha256) {
        Entry e = entries.get(sha256);
        return e != null ? e : new Entry(Verifier.Status.UNVERIFIED, "not in the registry");
    }

    /** When the index was last known to be current: generated, or later confirmed by a timestamp. */
    public Instant confirmedAt() {
        return confirmedAt;
    }

    /**
     * This index, confirmed as current at {@code at} by a valid timestamp. The confirmation counts
     * for at most {@link #MAX_CONFIRMED_AGE} after the index was generated.
     */
    public Index confirmedAt(Instant at) {
        Instant limit = generatedAt.plus(MAX_CONFIRMED_AGE).minus(MAX_AGE);
        Instant capped = at.isAfter(limit) ? limit : at;
        return capped.isAfter(confirmedAt) ? new Index(generatedAt, registryCommit, entries, capped, notes, reviewers) : this;
    }

    public boolean isStale(Instant now) {
        return confirmedAt.plus(MAX_AGE).isBefore(now);
    }

    public static Index parse(Path file) throws IOException, Toml.TomlException {
        Map<String, Object> doc = Toml.parse(file);
        Object format = doc.get("format");
        if (!(format instanceof Long f) || f != FORMAT) {
            throw new IOException(file + ": unsupported index format " + format);
        }
        Instant generated;
        try {
            generated = Instant.parse(String.valueOf(Toml.string(doc, "generated_at")));
        } catch (DateTimeParseException e) {
            throw new IOException(file + ": invalid generated_at");
        }
        Map<String, Entry> entries = new LinkedHashMap<>();
        // Order matters: a hash listed in several sections gets the most severe status.
        for (Map.Entry<String, Verifier.Status> section : List.of(
                Map.entry("verified", Verifier.Status.VERIFIED),
                Map.entry("flagged", Verifier.Status.FLAGGED),
                Map.entry("blocked", Verifier.Status.BLOCKED))) {
            for (Map.Entry<String, Object> e : Toml.table(doc, section.getKey()).entrySet()) {
                if (!Hashing.isSha256Hex(e.getKey())) {
                    throw new IOException(file + ": invalid hash '" + e.getKey() + "'");
                }
                entries.put(e.getKey(), new Entry(section.getValue(), String.valueOf(e.getValue())));
            }
        }
        for (Map.Entry<String, Object> e : Toml.table(doc, "compat").entrySet()) {
            Entry known = entries.get(e.getKey());
            if (known != null && known.status() == Verifier.Status.VERIFIED) {
                entries.put(e.getKey(), new Entry(known.status(), known.label(), String.valueOf(e.getValue())));
            }
        }
        Map<String, String> notes = new LinkedHashMap<>();
        for (Map.Entry<String, Object> e : Toml.table(doc, "notes").entrySet()) {
            if (Hashing.isSha256Hex(e.getKey())) {
                notes.put(e.getKey(), String.valueOf(e.getValue()));
            }
        }
        Map<String, List<String>> reviewers = new LinkedHashMap<>();
        for (Map.Entry<String, Object> e : Toml.table(doc, "reviewers").entrySet()) {
            if (Hashing.isSha256Hex(e.getKey())) {
                reviewers.put(e.getKey(), List.of(String.valueOf(e.getValue()).split(",")).stream()
                        .map(String::strip).filter(s -> !s.isEmpty()).toList());
            }
        }
        return new Index(generated, Toml.string(doc, "registry_commit"), entries, generated, notes, reviewers);
    }

    /** Builds the index text from a registry checkout. Sign the written file with the registry key. */
    public static String generate(Registry registry, Verifier verifier, Instant now, String registryCommit)
            throws IOException, Toml.TomlException {
        Map<String, String> verified = new TreeMap<>();
        Map<String, String> flagged = new TreeMap<>();
        Map<String, String> blocked = new TreeMap<>();
        Map<String, String> compat = new TreeMap<>();
        Map<String, String> notes = new TreeMap<>();
        Map<String, String> reviewers = new TreeMap<>();
        for (Path buildFile : registry.buildFiles()) {
            for (String sha : Registry.jarHashes(registry.read(buildFile))) {
                Verifier.Result r = verifier.verifyHash(sha);
                // open info and suspicion flags: players see them whatever the status
                List<String> flagNotes = r.messages().stream()
                        .filter(m -> m.startsWith("open info flag") || m.startsWith("open suspicion flag")).toList();
                if (!flagNotes.isEmpty()) {
                    notes.put(sha, String.join("; ", flagNotes));
                }
                String label = r.mod() + " " + r.version()
                        + ("published".equals(r.method()) ? " (published binary, reviewed against source)"
                                : "workshop".equals(r.method()) ? " (Steam Workshop jar, rebuilt from source)" : "");
                switch (r.status()) {
                    // a granted exception for hard findings stays visible to the player
                    case VERIFIED -> {
                        List<String> rebuilt = Rebuilds.of(registry, r.mod(), r.version());
                        verified.put(sha, label + r.messages().stream()
                                .filter(m -> m.startsWith("hard findings (")).map(m -> "; " + m).findFirst().orElse("")
                                + (rebuilt.isEmpty() ? "" : "; rebuilt independently by " + String.join(", ", rebuilt)));
                        List<String> by = r.messages().stream().filter(m -> m.startsWith("approved by '"))
                                .map(m -> m.substring("approved by '".length(), m.indexOf('\'', "approved by '".length())))
                                .toList();
                        if (!by.isEmpty()) {
                            reviewers.put(sha, String.join(",", by));
                        }
                        String made = Compat.describe(registry.read(registry.releaseFile(r.mod(), r.version())));
                        if (made != null) {
                            compat.put(sha, made);
                        }
                    }
                    case FLAGGED -> flagged.put(sha, label + ": " + lastMessage(r));
                    case BLOCKED -> blocked.put(sha, label + ": " + lastMessage(r));
                    default -> {
                        // unverified or invalid: not listed, the launcher treats it as unverified
                    }
                }
            }
        }
        // review notes on closed-source jars (findings only, no code), signed by a reviewer
        for (ReviewNotes.Note n : ReviewNotes.valid(registry)) {
            notes.merge(n.sha256(), "review note by '" + n.reviewer() + "': " + n.findings(), (a, b) -> a + "; " + b);
        }
        Map<String, Object> blocklist = Toml.table(blocklistDoc(registry), "blocked");
        for (Map.Entry<String, Object> e : blocklist.entrySet()) {
            if (Hashing.isSha256Hex(e.getKey())) {
                blocked.put(e.getKey(), String.valueOf(e.getValue()));
                verified.remove(e.getKey());
                flagged.remove(e.getKey());
                compat.remove(e.getKey());
                reviewers.remove(e.getKey());
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("# BiteCheck index - generated by CI, signed by the registry key. Do not edit.\n");
        out.append("format = ").append(FORMAT).append('\n');
        out.append("generated_at = ").append(Toml.quote(now.truncatedTo(ChronoUnit.SECONDS).toString())).append('\n');
        out.append("registry_commit = ").append(Toml.quote(registryCommit == null ? "" : registryCommit)).append('\n');
        appendSection(out, "verified", verified);
        appendSection(out, "flagged", flagged);
        appendSection(out, "blocked", blocked);
        if (!compat.isEmpty()) {
            appendSection(out, "compat", compat);
        }
        if (!reviewers.isEmpty()) {
            appendSection(out, "reviewers", reviewers);
        }
        if (!notes.isEmpty()) {
            appendSection(out, "notes", notes);
        }
        return out.toString();
    }

    private static Map<String, Object> blocklistDoc(Registry registry) throws IOException, Toml.TomlException {
        Path file = registry.root().resolve("registry").resolve("blocklist.toml");
        return java.nio.file.Files.isRegularFile(file) ? Toml.parse(file) : Map.of();
    }

    private static String lastMessage(Verifier.Result r) {
        return r.messages().isEmpty() ? "" : r.messages().get(r.messages().size() - 1);
    }

    private static void appendSection(StringBuilder out, String name, Map<String, String> entries) {
        out.append("\n[").append(name).append("]\n");
        for (Map.Entry<String, String> e : entries.entrySet()) {
            out.append(e.getKey()).append(" = ").append(Toml.quote(e.getValue())).append('\n');
        }
    }
}
