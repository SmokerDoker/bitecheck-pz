package io.github.bitecheckpz.core;

import java.io.IOException;
import java.nio.file.Path;
import java.time.Duration;
import java.time.Instant;
import java.time.format.DateTimeParseException;
import java.time.temporal.ChronoUnit;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The signed index the launcher downloads: one small file with the verification status of every
 * jar the registry knows, so players do not need a full registry checkout.
 *
 * <pre>
 * format = 1
 * generated_at = "2026-11-01T10:00:00Z"
 * registry_commit = "…"
 * [verified]
 * &lt;jar sha256&gt; = "mod-id 1.0.0"
 * [flagged]
 * &lt;jar sha256&gt; = "mod-id 1.0.0: reason"
 * [blocked]
 * &lt;jar sha256&gt; = "reason"
 * </pre>
 *
 * <p>The index is generated by CI from the registry ({@link #generate}) and signed with the registry
 * key. Jars that are not listed are unverified.
 */
public final class Index {

    public static final int FORMAT = 1;
    /** After this age, verified entries are no longer trusted (blocked entries still apply). */
    public static final Duration MAX_AGE = Duration.ofDays(7);
    /** Tolerated clock difference for indexes that seem to come from the future. */
    public static final Duration CLOCK_SKEW = Duration.ofHours(1);

    public record Entry(Verifier.Status status, String label) {
    }

    private final Instant generatedAt;
    private final String registryCommit;
    private final Map<String, Entry> entries;

    private Index(Instant generatedAt, String registryCommit, Map<String, Entry> entries) {
        this.generatedAt = generatedAt;
        this.registryCommit = registryCommit;
        this.entries = entries;
    }

    public Instant generatedAt() {
        return generatedAt;
    }

    public String registryCommit() {
        return registryCommit;
    }

    public Map<String, Entry> entries() {
        return entries;
    }

    /** Status of a jar hash: VERIFIED, FLAGGED, BLOCKED or UNVERIFIED (not listed). */
    public Entry lookup(String sha256) {
        Entry e = entries.get(sha256);
        return e != null ? e : new Entry(Verifier.Status.UNVERIFIED, "not in the registry");
    }

    public boolean isStale(Instant now) {
        return generatedAt.plus(MAX_AGE).isBefore(now);
    }

    public static Index parse(Path file) throws IOException, Toml.TomlException {
        Map<String, Object> doc = Toml.parse(file);
        Object format = doc.get("format");
        if (!(format instanceof Long f) || f != FORMAT) {
            throw new IOException(file + ": unsupported index format " + format);
        }
        Instant generated;
        try {
            generated = Instant.parse(String.valueOf(Toml.string(doc, "generated_at")));
        } catch (DateTimeParseException e) {
            throw new IOException(file + ": invalid generated_at");
        }
        Map<String, Entry> entries = new LinkedHashMap<>();
        // Order matters: a hash listed in several sections gets the most severe status.
        for (Map.Entry<String, Verifier.Status> section : List.of(
                Map.entry("verified", Verifier.Status.VERIFIED),
                Map.entry("flagged", Verifier.Status.FLAGGED),
                Map.entry("blocked", Verifier.Status.BLOCKED))) {
            for (Map.Entry<String, Object> e : Toml.table(doc, section.getKey()).entrySet()) {
                if (!Hashing.isSha256Hex(e.getKey())) {
                    throw new IOException(file + ": invalid hash '" + e.getKey() + "'");
                }
                entries.put(e.getKey(), new Entry(section.getValue(), String.valueOf(e.getValue())));
            }
        }
        return new Index(generated, Toml.string(doc, "registry_commit"), entries);
    }

    /** Builds the index text from a registry checkout. Sign the written file with the registry key. */
    public static String generate(Registry registry, Verifier verifier, Instant now, String registryCommit)
            throws IOException, Toml.TomlException {
        Map<String, String> verified = new TreeMap<>();
        Map<String, String> flagged = new TreeMap<>();
        Map<String, String> blocked = new TreeMap<>();
        for (Path buildFile : registry.buildFiles()) {
            for (String sha : Registry.jarHashes(registry.read(buildFile))) {
                Verifier.Result r = verifier.verifyHash(sha);
                String label = r.mod() + " " + r.version()
                        + ("published".equals(r.method()) ? " (published binary, reviewed against source)" : "");
                switch (r.status()) {
                    case VERIFIED -> verified.put(sha, label);
                    case FLAGGED -> flagged.put(sha, label + ": " + lastMessage(r));
                    case BLOCKED -> blocked.put(sha, label + ": " + lastMessage(r));
                    default -> {
                        // unverified or invalid: not listed, the launcher treats it as unverified
                    }
                }
            }
        }
        Map<String, Object> blocklist = Toml.table(blocklistDoc(registry), "blocked");
        for (Map.Entry<String, Object> e : blocklist.entrySet()) {
            if (Hashing.isSha256Hex(e.getKey())) {
                blocked.put(e.getKey(), String.valueOf(e.getValue()));
                verified.remove(e.getKey());
                flagged.remove(e.getKey());
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("# BiteCheck index - generated by CI, signed by the registry key. Do not edit.\n");
        out.append("format = ").append(FORMAT).append('\n');
        out.append("generated_at = ").append(Toml.quote(now.truncatedTo(ChronoUnit.SECONDS).toString())).append('\n');
        out.append("registry_commit = ").append(Toml.quote(registryCommit == null ? "" : registryCommit)).append('\n');
        appendSection(out, "verified", verified);
        appendSection(out, "flagged", flagged);
        appendSection(out, "blocked", blocked);
        return out.toString();
    }

    private static Map<String, Object> blocklistDoc(Registry registry) throws IOException, Toml.TomlException {
        Path file = registry.root().resolve("registry").resolve("blocklist.toml");
        return java.nio.file.Files.isRegularFile(file) ? Toml.parse(file) : Map.of();
    }

    private static String lastMessage(Verifier.Result r) {
        return r.messages().isEmpty() ? "" : r.messages().get(r.messages().size() - 1);
    }

    private static void appendSection(StringBuilder out, String name, Map<String, String> entries) {
        out.append("\n[").append(name).append("]\n");
        for (Map.Entry<String, String> e : entries.entrySet()) {
            out.append(e.getKey()).append(" = ").append(Toml.quote(e.getValue())).append('\n');
        }
    }
}
